export function resolveLocale(saved: string | null, browserLanguage: string): Locale {
  if (saved === 'zh' || saved === 'en') return saved;
  return browserLanguage.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function text(locale: Locale, key: TextKey, values: Record<string, string | number> = {}): string {
  return catalogs[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  ));
}

export function metric(locale: Locale, key: MetricKey): MetricCopy {
  return metrics[locale][key];
}
